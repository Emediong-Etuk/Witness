const host = (r: AuditResult['remotes'][number]) => (r.hostnames[0] ? `${r.hostnames[0]} (${r.ip})` : r.ip);

/** Markdown generated from bench/out/egress/*.json. Numbers only; no prose. */
export function renderEgress(results: AuditResult[]): string {
  const L: string[] = ['<!-- generated by npm run egress:report from bench/out/egress/*.json; do not edit -->', ''];
  if (!results.length) return L.concat('_No audit runs yet._', '').join('\n');
  L.push('| Config | Sampler | Duration s | Samples | Insights received (unrequested) | Metrics packets | SDK errors |', '| --- | --- | --- | --- | --- | --- | --- |');
  for (const r of results) {
    const p = (r.probe ?? {}) as { insightsUnrequested?: number | null; metricsPackets?: number; errors?: unknown[] };
    L.push(`| ${r.label} | ${r.sampler} | ${r.durationS} | ${r.samples} | ${p.insightsUnrequested ?? 'n/a'} | ${p.metricsPackets ?? 'n/a'} | ${p.errors?.length ?? 'n/a'} |`);
  }
  L.push('', '**Remote endpoints (socket tables):**', '', '| Config | Remote (reverse DNS) | Proto | Port | First s | Last s | Samples seen |', '| --- | --- | --- | --- | --- | --- | --- |');
  for (const r of results) {
    if (!r.remotes.length) L.push(`| ${r.label} | none observed | | | | | |`);
    for (const x of r.remotes) L.push(`| ${r.label} | ${host(x)} | ${x.proto} | ${x.port} | ${x.firstS} | ${x.lastS} | ${x.seen} |`);
  }
  const withProxy = results.filter((r) => r.proxy.used);
  if (withProxy.length) {
    L.push('', '**Requested hostnames (logging CONNECT proxy; only if the process honours proxy variables):**', '', '| Config | Host | Port | First s | Last s | Count |', '| --- | --- | --- | --- | --- | --- |');
    for (const r of withProxy) {
      if (!r.proxy.connects.length) L.push(`| ${r.label} | none (process did not use the proxy) | | | | |`);
      for (const c of r.proxy.connects) L.push(`| ${r.label} | ${c.host} | ${c.port} | ${c.firstS} | ${c.lastS} | ${c.count} |`);
    }
  }
  // Hosts present in one config but not another: the §7.6 (a) vs (b) comparison.
  const a = results.find((r) => r.label.startsWith('a-'));
  const b = results.find((r) => r.label.startsWith('b-'));
  if (a && b) {
    const key = (x: AuditResult['remotes'][number]) => `${x.hostnames[0] ?? x.ip}:${x.port}`;
    const ka = new Set(a.remotes.map(key)), kb = new Set(b.remotes.map(key));
    L.push('', `Endpoints only in (a): ${[...ka].filter((k) => !kb.has(k)).join(', ') || 'none'} · only in (b): ${[...kb].filter((k) => !ka.has(k)).join(', ') || 'none'}`);
  }
  return L.join('\n') + '\n';
}

export function replaceBetween(doc: string, start: string, end: string, body: string): string {
  const i = doc.indexOf(start), j = doc.indexOf(end);
  if (i < 0 || j < 0 || j < i) throw new Error(`markers ${start} … ${end} not found`);
  return doc.slice(0, i + start.length) + '\n' + body + doc.slice(j);
}
